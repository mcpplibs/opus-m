#!/usr/bin/env python3
"""The public surface of libopus 1.6.1, opusfile 0.12 and libogg 1.3.6, from the pinned releases.

Shared by tools/gen_exports.py (which writes the module sources and the
generated tests), tools/check_exports.py (which audits them) and
tools/run_conformance.py (which needs upstream's opus_compare.c). The headers
come from the release tarballs, downloaded once into target/upstream and
checked against upstream/documents.json: the same bytes compat.opus,
compat.opusfile and compat.ogg build.

The public headers are the ones upstream installs:

  libopus   opus.h, opus_defines.h, opus_types.h, opus_multistream.h,
            opus_projection.h (Makefile.am pkginclude_HEADERS; opus_custom.h
            only with --enable-custom-modes, which compat.opus does not use)
  opusfile  opusfile.h
  libogg    ogg/ogg.h, ogg/os_types.h (ogg/config_types.h is generated by the
            build — compat.ogg's generated_files — and declares only the
            ogg_int*_t typedefs os_types.h declares on Windows and Apple)

Each header is read as text with its comments and preprocessor lines removed;
every declaration must be one the inventory recognises (a struct, a typedef,
a function), or it stops. Declarations in the branches of a platform
`#if` (opus_types.h, os_types.h) are the same names in every branch.
"""
from dataclasses import dataclass, field
import hashlib
import json
from pathlib import Path
import re
import sys
import tarfile
import time
import urllib.request

# module -> [(archive, path inside the archive's top directory)]
HEADERS = {
    'codec': [('opus', 'include/opus_types.h'), ('opus', 'include/opus_defines.h'), ('opus', 'include/opus.h'),
              ('opus', 'include/opus_multistream.h'), ('opus', 'include/opus_projection.h')],
    'ogg': [('ogg', 'include/ogg/os_types.h'), ('ogg', 'include/ogg/ogg.h')],
    'file': [('opusfile', 'include/opusfile.h')],
}

# libopusurl: declared in <opusfile.h>, defined in src/http.c, which
# compat.opusfile does not build (HTTP(S) streaming over OpenSSL).
URL_TYPES = {'OpusServerInfo'}
URL_FUNCTIONS = {'opus_server_info_init', 'opus_server_info_clear', 'op_url_stream_vcreate', 'op_url_stream_create',
                 'op_vopen_url', 'op_open_url', 'op_vtest_url', 'op_test_url'}
URL_MACROS = {'OP_SSL_SKIP_CERTIFICATE_CHECK_REQUEST', 'OP_HTTP_PROXY_HOST_REQUEST', 'OP_HTTP_PROXY_PORT_REQUEST',
              'OP_HTTP_PROXY_USER_REQUEST', 'OP_HTTP_PROXY_PASS_REQUEST', 'OP_GET_SERVER_INFO_REQUEST', 'OP_URL_OPT',
              'OP_CHECK_INT', 'OP_CHECK_CONST_CHAR_PTR', 'OP_CHECK_SERVER_INFO_PTR', 'OP_SSL_SKIP_CERTIFICATE_CHECK',
              'OP_HTTP_PROXY_HOST', 'OP_HTTP_PROXY_PORT', 'OP_HTTP_PROXY_USER', 'OP_HTTP_PROXY_PASS',
              'OP_GET_SERVER_INFO'}

# Attribute and keyword macros that can stand before or after a declaration.
DECL_MACROS = r'\b(?:OPUS_EXPORT|OPUS_WARN_UNUSED_RESULT|OP_WARN_UNUSED_RESULT|extern)\b|\b(?:OPUS_ARG_NONNULL|OP_ARG_NONNULL)\s*\([^)]*\)'


def pins(root: Path) -> dict:
    return json.loads((root / 'upstream/documents.json').read_text(encoding='utf-8'))


def fetch_url(url: str, sha256: str, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or hashlib.sha256(path.read_bytes()).hexdigest() != sha256:
        # A few attempts: CI's runners meet the occasional dropped TLS connection.
        for attempt in range(1, 6):
            print('+ fetch', url, f'(attempt {attempt})' if attempt > 1 else '', flush=True)
            try:
                request = urllib.request.Request(url, headers={'User-Agent': 'opus-m-tools/1.0'})
                with urllib.request.urlopen(request, timeout=300) as response:
                    path.write_bytes(response.read())
                break
            except OSError as error:  # URLError, ssl.SSLError and timeouts are OSErrors
                print(f'  {error}', flush=True)
                if attempt == 5:
                    raise
                time.sleep(10 * attempt)
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != sha256:
        sys.exit(f'{url}: checksum {digest} != {sha256}')
    return path


def fetch(root: Path) -> dict[str, Path]:
    """The extracted release trees, by archive name (opus, opusfile, ogg)."""
    cache = root / 'target/upstream'
    trees = {}
    for archive in pins(root)['archives']:
        tarball = fetch_url(archive['url'], archive['sha256'], cache / Path(archive['url']).name)
        with tarfile.open(tarball) as tar:
            top = tar.getmembers()[0].name.split('/')[0]
            if not (cache / top / 'include').exists():
                tar.extractall(cache, filter='data')
        trees[archive['name']] = cache / top
    return trees


@dataclass
class Macro:
    name: str
    header: str
    params: list[str] | None   # None: object-like
    body: str


@dataclass
class Surface:
    types: dict[str, list[str]] = field(default_factory=dict)      # module: typedef and struct names
    functions: dict[str, list[str]] = field(default_factory=dict)  # module: functions
    variadic: list[str] = field(default_factory=list)              # functions taking `...`
    macros: dict[str, Macro] = field(default_factory=dict)
    excluded_types: list[str] = field(default_factory=list)        # libopusurl
    excluded_functions: list[str] = field(default_factory=list)


def strip(text: str) -> str:
    text = re.sub(r'/\*.*?\*/', ' ', text, flags=re.S)
    return re.sub(r'//[^\n]*', '', text)


def balance(code: str) -> str:
    """Drop `extern "C" {` and the `}` that closed it (both behind #ifdef __cplusplus)."""
    code = re.sub(r'\bextern\s*"C"\s*\{', ' ', code)
    out, depth = [], 0
    for ch in code:
        if ch == '{':
            depth += 1
        elif ch == '}':
            if depth == 0:
                continue
            depth -= 1
        out.append(ch)
    return ''.join(out)


def surface(trees: dict[str, Path]) -> Surface:
    s = Surface()
    for module, headers in HEADERS.items():
        types, functions = set(), set()
        for archive, path in headers:
            name = path.split('/', 1)[1]
            text = strip((trees[archive] / path).read_text(encoding='utf-8'))
            for m in re.finditer(r'^[ \t]*#[ \t]*define[ \t]+(\w+)(\(([^)]*)\))?[ \t]*((?:[^\n]*\\\n)*[^\n]*)', text, flags=re.M):
                params = [p.strip() for p in m.group(3).split(',')] if m.group(2) else None
                body = ' '.join(m.group(4).replace('\\\n', ' ').split())
                s.macros.setdefault(m.group(1), Macro(m.group(1), name, params, body))
            code = re.sub(r'^[ \t]*#(?:[^\n]*\\\n)*[^\n]*', '', text, flags=re.M)
            code = balance(code)
            # Named struct definitions (opusfile: `struct OpusHead{ … };`).
            for m in re.finditer(r'(?<!typedef )\bstruct\s+(\w+)\s*\{.*?\}\s*;', code, flags=re.S):
                types.add(m.group(1))
            code = re.sub(r'(?<!typedef )\bstruct\s+\w+\s*\{.*?\}\s*;', ';', code, flags=re.S)
            # Unnamed struct typedefs (libogg: `typedef struct { … } ogg_page;`).
            for m in re.finditer(r'\btypedef\s+struct\s*\{.*?\}\s*(\w+)\s*;', code, flags=re.S):
                types.add(m.group(1))
            code = re.sub(r'\btypedef\s+struct\s*\{.*?\}\s*\w+\s*;', ';', code, flags=re.S)
            # Opaque and forward typedefs: `typedef struct OpusEncoder OpusEncoder;`.
            for m in re.finditer(r'\btypedef\s+struct\s+(\w+)\s+(\w+)\s*;', code):
                if m.group(1) != m.group(2):
                    sys.exit(f'{name}: typedef struct {m.group(1)} {m.group(2)}: a tag of another name')
                types.add(m.group(2))
            code = re.sub(r'\btypedef\s+struct\s+\w+\s+\w+\s*;', ';', code)
            # Function pointer types: `typedef int (*op_read_func)(void *_stream, …);`.
            types.update(re.findall(r'\btypedef\b[^;(]*\(\s*\*\s*(\w+)\s*\)\s*\([^;]*\)\s*;', code))
            code = re.sub(r'\btypedef\b[^;(]*\(\s*\*\s*\w+\s*\)\s*\([^;]*\)\s*;', ';', code)
            # Plain typedefs: `typedef int32_t opus_int32;`, `typedef unsigned __int64 ogg_uint64_t;`.
            types.update(re.findall(r'\btypedef\s+[\w\s\*]+?\b(\w+)\s*;', code))
            code = re.sub(r'\btypedef\b[^;]*;', ';', code)
            # Functions: whatever is left, attributes aside.
            for decl in code.split(';'):
                decl = ' '.join(re.sub(DECL_MACROS, ' ', decl).split())
                if not decl:
                    continue
                f = re.match(r'^[\w\s\*]*?\b(\w+)\s*\((.*)\)$', decl, flags=re.S)
                if not f:
                    sys.exit(f'{name}: a declaration the inventory does not know: {decl[:200]}')
                functions.add(f.group(1))
                if re.search(r'\.\.\.\s*$', f.group(2)):
                    s.variadic.append(f.group(1))
        s.excluded_types += sorted(types & URL_TYPES)
        s.excluded_functions += sorted(functions & URL_FUNCTIONS)
        s.types[module] = sorted(types - URL_TYPES)
        s.functions[module] = sorted(functions - URL_FUNCTIONS)
    s.variadic = sorted(set(s.variadic))
    return s


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    sf = surface(fetch(root))
    for module in HEADERS:
        print(f'{module}: {len(sf.types[module])} types, {len(sf.functions[module])} functions')
        print('  types:', ' '.join(sf.types[module]))
        print('  functions:', ' '.join(sf.functions[module]))
    print('variadic:', ' '.join(sf.variadic))
    print('libopusurl (not built):', ' '.join(sf.excluded_types + sf.excluded_functions))
    print(f'{len(sf.macros)} macros')
    print('object-like:', ' '.join(m.name for m in sf.macros.values() if m.params is None))
    print('function-like:', ' '.join(m.name for m in sf.macros.values() if m.params is not None))
